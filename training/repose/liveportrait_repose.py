#!/usr/bin/env python3
"""
Method C: re-pose real faces with LivePortrait
==============================================
Takes faces from the source pool (output of prepare_faces.py), generates new images at target poses, then hands them back to prepare_faces.py
to re-detect landmarks and pose and drop failures (samples whose measured pose is more than 15 deg from the target are discarded).

  # 1) measure LivePortrait's angle signs and usable range (writes a grid image + a measurement table)
  python training/repose/liveportrait_repose.py probe --pool data/faces_pool --out data/repose_probe

  # 2) batch generation: several target poses per base image, sampled from the training pose distribution
  python training/repose/liveportrait_repose.py batch --pool data/faces_pool --out data/repose_lp --per_base 6
  python training/prepare_faces.py --src data/repose_lp --out data/faces_pool --dataset repose_lp --min_face 60

  # 3) generate a video with a continuously changing pose (for the test-video benchmark)
  python training/repose/liveportrait_repose.py video --pool data/faces_pool --id 000123 --path "0,0;30,0;30,40;-30,-40" --out x.mp4

All angles follow the HeadPose convention (see training/common.py): pitch > 0 looking up, yaw > 0 turning to the subject's right, roll > 0 clockwise.
LivePortrait's internal convention and the conversion are in HP_TO_LP (measured by probe).

Roll is not generated by LivePortrait: training applies it exactly by a 2D rotation (method A), so the roll change defaults to 0 here.
"""
import argparse
import json
import os
import sys

import cv2
import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LP_DIR = os.path.join(ROOT, "third_party", "LivePortrait")
sys.path.insert(0, os.path.dirname(HERE))
from common import biggest  # noqa: E402

# HeadPose angle change -> LivePortrait input angle change (measured by probe, 3 base images x 7x7 grid):
#   adding d to LivePortrait's pitch changes the HeadPose pitch by about -0.86 d (its positive pitch = looking down); yaw changes by about +1.00 d.
#   roll was not measured and is not used (roll comes from the exact 2D rotation during training).
# usable range: single-axis pitch +-40 deg and yaw +-60 deg are mostly reached; pitch saturates beyond +-40 deg and yaw falls short in large combined poses;
# those cases are dropped by the target-pose check in prepare_faces.py.
HP_TO_LP = np.array([-1 / 0.86, 1.0, 1.0])
PAD = 256          # replicate-pad the source crops (mirror padding creates fake faces that get detected) to leave room for LivePortrait's crop


class LPRepose:
    def __init__(self, force_cpu=False):
        os.environ.setdefault("PYTORCH_ENABLE_MPS_FALLBACK", "1")
        sys.path.insert(0, LP_DIR)
        from src.config.inference_config import InferenceConfig
        from src.config.crop_config import CropConfig
        from src.live_portrait_wrapper import LivePortraitWrapper
        from src.utils.cropper import Cropper
        from src.utils.camera import get_rotation_matrix
        from src.utils.crop import prepare_paste_back, paste_back
        self._rot, self._prep_pb, self._pb = get_rotation_matrix, prepare_paste_back, paste_back
        self.icfg = InferenceConfig(flag_force_cpu=force_cpu)
        self.ccfg = CropConfig(flag_force_cpu=force_cpu)
        self.w = LivePortraitWrapper(inference_cfg=self.icfg)
        if self.w.device == "mps":
            # upstream does not use half precision on mps; the warping module (3D convolutions) takes 1.5 s/image; fp16 autocast brings it to 0.3 s with < 0.1% output difference
            self.w.inference_ctx = lambda: torch.autocast("mps", dtype=torch.float16)
        self.cropper = Cropper(crop_cfg=self.ccfg, flag_force_cpu=force_cpu)

    @torch.no_grad()
    def prepare(self, img_bgr):
        """One image (may be a 512 crop from the source pool) -> intermediate state for re-posing; None if no face is detected."""
        padded = cv2.copyMakeBorder(img_bgr, PAD, PAD, PAD, PAD, cv2.BORDER_REPLICATE)
        rgb = cv2.cvtColor(padded, cv2.COLOR_BGR2RGB)
        ci = self.cropper.crop_source_image(rgb, self.ccfg)
        if ci is None:
            return None
        I_s = self.w.prepare_source(ci["img_crop_256x256"])
        info = self.w.get_kp_info(I_s)
        st = dict(rgb=rgb, M_c2o=ci["M_c2o"], f_s=self.w.extract_feature_3d(I_s), info=info,
                  x_s=self.w.transform_keypoint(info),
                  mask=self._prep_pb(self.icfg.mask_crop, ci["M_c2o"], dsize=(rgb.shape[1], rgb.shape[0])),
                  lp_pose=np.array([float(info[k]) for k in ("pitch", "yaw", "roll")]), size=img_bgr.shape[:2])
        return st

    @torch.no_grad()
    def render(self, st, d_hp, margin=0):
        """d_hp: (d_pitch, d_yaw, d_roll) in the HeadPose convention. Returns a BGR image covering the input plus margin extra pixels
        (so re-cropping the pipeline way needs no mirror padding, whose fake mirrored faces would confuse the detector)."""
        dev = self.w.device
        info = st["info"]
        d = np.asarray(d_hp, np.float64) * HP_TO_LP
        tgt = [info[k] + float(dk) for k, dk in zip(("pitch", "yaw", "roll"), d)]
        R_d = self._rot(*tgt)
        x_d = info["scale"] * (info["kp"] @ R_d + info["exp"]) + info["t"]
        x_d = self.w.stitching(st["x_s"], x_d)
        out = self.w.warp_decode(st["f_s"], st["x_s"], x_d.to(dev))
        crop = self.w.parse_output(out["out"])[0]
        full = self._pb(crop, st["M_c2o"], st["rgb"], st["mask"])
        h, w = st["size"]
        m = min(margin, PAD)
        return cv2.cvtColor(full[PAD - m:PAD + h + m, PAD - m:PAD + w + m], cv2.COLOR_RGB2BGR)


def load_pool(pool):
    with open(os.path.join(pool, "index.jsonl")) as f:
        return [json.loads(l) for l in f if l.strip()]


def pick_bases(recs, n, seed=0, max_abs=20.0):
    """Pick near-frontal base images from diverse sources (accurate landmarks, little warping after re-posing)."""
    rng = np.random.default_rng(seed)
    ok = [r for r in recs if r.get("method", "real") == "real"
          and abs(r["pitch"]) < max_abs and abs(r["yaw"]) < max_abs]
    by_src = {}
    for r in ok:
        by_src.setdefault((r["dataset"], r["src"]), []).append(r)
    groups = list(by_src.values())
    out = []
    while len(out) < n and any(groups):
        for g in groups:
            if g and len(out) < n:
                out.append(g.pop(int(rng.integers(len(g)))))
    return out


def sample_target(rng, lim_p=50.0, lim_y=75.0):
    """Training sampling distribution (pitch and yaw only): 50% uniform over the full range, 30% one axis at a large angle, 20% combined large angles."""
    u = rng.random()
    if u < 0.5:
        return np.array([rng.uniform(-lim_p, lim_p), rng.uniform(-lim_y, lim_y), 0.0])
    if u < 0.8:
        if rng.random() < 0.5:
            return np.array([rng.choice([-1, 1]) * rng.uniform(0.6, 1.0) * lim_p, rng.uniform(-15, 15), 0.0])
        return np.array([rng.uniform(-15, 15), rng.choice([-1, 1]) * rng.uniform(0.6, 1.0) * lim_y, 0.0])
    return np.array([rng.choice([-1, 1]) * rng.uniform(25, lim_p), rng.choice([-1, 1]) * rng.uniform(25, lim_y), 0.0])


