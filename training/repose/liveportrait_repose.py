def cmd_probe(a):
    """Run a d_pitch x d_yaw grid on a few base images and measure the actual HeadPose change to determine signs and usable range."""
    from uniface import RetinaFace, HeadPose
    det, hp = RetinaFace(), HeadPose()
    lp = LPRepose()
    os.makedirs(a.out, exist_ok=True)
    recs = load_pool(a.pool)
    bases = pick_bases(recs, a.n_bases, seed=1)
    dps = [-45, -30, -15, 0, 15, 30, 45]
    dys = [-60, -40, -20, 0, 20, 40, 60]
    rows = []
    for b in bases:
        img = cv2.imread(os.path.join(a.pool, "faces", b["id"] + ".jpg"))
        st = lp.prepare(img)
        if st is None:
            continue
        p0 = np.array([b["pitch"], b["yaw"], b["roll"]])
        grid = []
        for dp in dps:
            line = []
            for dy in dys:
                out = lp.render(st, (dp, dy, 0))
                f = det.detect(out)
                meas = None
                if f:
                    x1, y1, x2, y2 = [int(max(0, v)) for v in biggest(f).bbox[:4]]
                    r = hp.estimate(out[y1:y2, x1:x2])
                    meas = np.array([r.pitch, r.yaw, r.roll]) - p0
                rows.append(dict(id=b["id"], dp=dp, dy=dy, lp_pose=st["lp_pose"].round(1).tolist(),
                                 meas=None if meas is None else meas.round(1).tolist()))
                t = out.copy()
                txt = "nodet" if meas is None else f"{meas[0]:+.0f},{meas[1]:+.0f}"
                cv2.putText(t, f"d{dp:+d},{dy:+d} m{txt}", (6, 30), 0, 0.9, (0, 255, 0), 2)
                line.append(cv2.resize(t, (200, 200), interpolation=cv2.INTER_AREA))
            grid.append(np.hstack(line))
        cv2.imwrite(os.path.join(a.out, f"probe_{b['id']}.jpg"), np.vstack(grid), [cv2.IMWRITE_JPEG_QUALITY, 85])
    with open(os.path.join(a.out, "probe.json"), "w") as f:
        json.dump(rows, f)
    ok = [r for r in rows if r["meas"] is not None]
    D = np.array([[r["dp"], r["dy"]] for r in ok], float)
    Mm = np.array([r["meas"][:2] for r in ok], float)
    for k, nm in enumerate(("pitch", "yaw")):
        sel = np.abs(D[:, 1 - k]) <= 0.1   # samples that change this axis only
        c = np.polyfit(D[sel, k], Mm[sel, k], 1)
        print(f"{nm}: HeadPose change ~ {c[0]:+.2f} x input change {c[1]:+.1f} (single-axis samples {sel.sum()})")
    print(f"detection failed {len(rows) - len(ok)}/{len(rows)}; grid image at {a.out}")


def cmd_batch(a):
    lp = LPRepose()
    os.makedirs(a.out, exist_ok=True)
    rng = np.random.default_rng(a.seed)
    recs = load_pool(a.pool)
    if a.sparse_below:
        return batch_sparse(a, lp, rng, recs)
    bases = pick_bases(recs, a.n_bases, seed=a.seed)
    n = 0
    for bi, b in enumerate(bases):
        img = cv2.imread(os.path.join(a.pool, "faces", b["id"] + ".jpg"))
        st = lp.prepare(img)
        if st is None:
            continue
        p0 = np.array([b["pitch"], b["yaw"], 0.0])
        for k in range(a.per_base):
            tgt = sample_target(rng, a.max_pitch, a.max_yaw)
            out = lp.render(st, (tgt - p0) * a.gain, margin=96)
            name = f"{b['id']}_lp{k:02d}"
            cv2.imwrite(os.path.join(a.out, name + ".jpg"), out, [cv2.IMWRITE_JPEG_QUALITY, 95])
            with open(os.path.join(a.out, name + ".json"), "w") as f:
                json.dump(dict(method="liveportrait", base_id=b["id"],
                               base_npz=os.path.abspath(os.path.join(a.pool, "faces", b["id"] + ".npz")),
                               target_pose=[round(float(tgt[0]), 1), round(float(tgt[1]), 1), b["roll"]]), f)
            n += 1
        print(f"  base image {bi + 1}/{len(bases)}, {n} generated", end="\r", flush=True)
    print(f"\ndone: {n} images -> {a.out}")


def batch_sparse(a, lp, rng, recs):
    """Targeted filling of rare cells: targets come from sparsely populated pitch x yaw cells; base images are real faces close to a reachable pose (the smaller the rotation, the better)."""
    from repose.targets import pick_base, sparse_cells
    targets = sparse_cells(recs, a.sparse_below)
    bases = [r for r in recs if r.get("method", "real") == "real" and r.get("kps_err", 1.0) <= 0.08
             and abs(r["pitch"]) < 25 and abs(r["yaw"]) < 40]
    bp = np.array([[r["pitch"], r["yaw"]] for r in bases], np.float32)
    print(f"{len(targets)} rare cells, {len(bases)} candidate base images")
    n = 0
    for k in range(a.n_bases * a.per_base):
        t = np.array(targets[int(rng.integers(len(targets)))]) + rng.uniform(-5, 5, 2)
        j = pick_base(rng, bp, t, reach=60)
        if j is None:
            continue
        b = bases[j]
        img = cv2.imread(os.path.join(a.pool, "faces", b["id"] + ".jpg"))
        st = lp.prepare(img)
        if st is None:
            continue
        tgt = np.array([t[0], t[1], 0.0])
        p0 = np.array([b["pitch"], b["yaw"], 0.0])
        out = lp.render(st, (tgt - p0) * a.gain, margin=96)
        name = f"{b['id']}_sp{k:05d}"
        cv2.imwrite(os.path.join(a.out, name + ".jpg"), out, [cv2.IMWRITE_JPEG_QUALITY, 95])
        with open(os.path.join(a.out, name + ".json"), "w") as f:
            json.dump(dict(method="liveportrait", base_id=b["id"],
                           base_npz=os.path.abspath(os.path.join(a.pool, "faces", b["id"] + ".npz")),
                           target_pose=[round(float(t[0]), 1), round(float(t[1]), 1), b["roll"]]), f)
        n += 1
        print(f"  {k + 1}/{a.n_bases * a.per_base}, {n} generated", end="\r", flush=True)
    print(f"\ndone: {n} images -> {a.out}")


def cmd_video(a):
    """Interpolate along a polyline of key poses to generate a video with a continuously changing pose (fps frames per second, seg_sec seconds per segment)."""
    lp = LPRepose()
    img = cv2.imread(os.path.join(a.pool, "faces", a.id + ".jpg"))
    st = lp.prepare(img)
    assert st is not None, "no face detected in the base image"
    rec = {r["id"]: r for r in load_pool(a.pool)}[a.id]
    p0 = np.array([rec["pitch"], rec["yaw"], 0.0])
    keys = [np.array([float(v) for v in s.split(",")] + [0.0])[:3] for s in a.path.split(";")]
    frames, poses = [], []
    n = int(a.seg_sec * a.fps)
    for k0, k1 in zip(keys[:-1], keys[1:]):
        for i in range(n):
            t = 0.5 - 0.5 * np.cos(np.pi * i / n)     # ease in / ease out
            tgt = k0 * (1 - t) + k1 * t
            frames.append(lp.render(st, (tgt - p0) * a.gain))
            poses.append(tgt.tolist())
    h, w = frames[0].shape[:2]
    vw = cv2.VideoWriter(a.out, cv2.VideoWriter_fourcc(*"mp4v"), a.fps, (w, h))
    for f in frames:
        vw.write(f)
    vw.release()
    with open(os.path.splitext(a.out)[0] + "_poses.json", "w") as f:
        json.dump(dict(base_id=a.id, fps=a.fps, target_poses=poses), f)
    print(f"{len(frames)} frames -> {a.out}")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("probe")
    p.add_argument("--pool", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--n_bases", type=int, default=3)
    p = sub.add_parser("batch")
    p.add_argument("--pool", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--n_bases", type=int, default=100)
    p.add_argument("--per_base", type=int, default=6)
    p.add_argument("--max_pitch", type=float, default=50)
    p.add_argument("--max_yaw", type=float, default=75)
    p.add_argument("--gain", type=float, default=1.0, help="input angle gain (compensates for LivePortrait under-rotating)")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--sparse_below", type=int, default=0, help=">0: fill pitch x yaw cells with fewer samples than this (n_bases x per_base images in total)")
    p = sub.add_parser("video")
    p.add_argument("--pool", required=True)
    p.add_argument("--id", required=True)
    p.add_argument("--path", required=True, help='key poses "pitch,yaw;pitch,yaw;..." (HeadPose convention)')
    p.add_argument("--out", required=True)
    p.add_argument("--fps", type=int, default=25)
    p.add_argument("--seg_sec", type=float, default=1.5)
    p.add_argument("--gain", type=float, default=1.0)
    a = ap.parse_args()
    dict(probe=cmd_probe, batch=cmd_batch, video=cmd_video)[a.cmd](a)


if __name__ == "__main__":
    main()
